"""Offline evidence observers receive each executed trial once and fail closed."""
import copy
import json
import sqlite3
import unittest
from unittest.mock import patch

import engine
import study


class StudyTrialObserverTests(unittest.TestCase):
    def test_real_rules_eight_arms_expose_sixteen_complete_trials_before_checkpoints(self):
        observed, checkpoints, order = [], [], []
        secret = "observer-test-not-a-real-credential"
        cfg = engine.Config(agent_mode="rules", model_config={"api_key": secret})

        def observe(sample, result):
            order.append(("trial", sample["execution_index"]))
            observed.append((sample, result))

        def checkpoint(report):
            order.append(("checkpoint", report["completed"]))
            checkpoints.append(report)

        report = study.run_study(cfg, {"repetitions": 2,
                                 "prompt_policies": ["neutral", "recovery"]},
                                 on_checkpoint=checkpoint, on_trial=observe)

        self.assertEqual((report["planned"], report["completed"], len(report["arms"])), (16, 16, 8))
        self.assertEqual(len(observed), 16)
        self.assertEqual(len(checkpoints), 17)
        self.assertEqual(order, [item for index in range(1, 17)
                                for item in (("trial", index), ("checkpoint", index))]
                         + [("checkpoint", 16)])
        for index, (sample, result) in enumerate(observed, 1):
            with self.subTest(execution_index=index):
                self.assertEqual(sample["execution_index"], index)
                self.assertEqual(sample["arm_id"], f"{sample['prompt_policy']}:{sample['strategy']}")
                self.assertEqual(sample, report["samples"][index - 1])
                self.assertEqual(sample["events"], result["events"])
                self.assertTrue(result["events"])
                self.assertTrue(result["sqlite_dump"].startswith("BEGIN TRANSACTION;"))
                self.assertNotIn("sqlite_dump", sample)
                # This dump is generated by the real local engine in this test.
                # The observer makes the same per-trial database export possible
                # without rerunning an agent or retaining the engine's connection.
                with sqlite3.connect(":memory:") as database:
                    database.executescript(result["sqlite_dump"])
                    rows = database.execute("SELECT COUNT(*) FROM reservations").fetchone()[0]
                self.assertEqual(rows, len(result["business_records"]))
        self.assertEqual(report["model_usage"]["requests"], 0)
        self.assertEqual({sample["arm_id"] for sample, _ in observed},
                         {f"{policy}:{strategy}" for policy in ("neutral", "recovery")
                          for strategy in study.STRATEGIES})
        self.assertNotIn(secret, json.dumps([report, observed]))
        self.assertTrue(all("model_config" not in result for _, result in observed))

    def test_mutating_either_observer_argument_cannot_change_source_or_report(self):
        originals, checkpoints = [], []
        execute = engine.run_trial

        def capture(*args, **kwargs):
            result = execute(*args, **kwargs)
            originals.append((result, copy.deepcopy(result)))
            return result

        def observe(sample, result):
            sample["events"].clear()
            sample["business_records"].clear()
            sample["stats"]["physical_writes"] = -900
            sample["arm_id"] = "mutated:sample"
            self.assertTrue(result["events"])
            self.assertTrue(result["business_records"])
            result["events"].clear()
            result["business_records"].clear()
            result["sqlite_dump"] = "mutated result"
            result["stats"]["physical_writes"] = -901

        with patch.object(engine, "run_trial", side_effect=capture):
            report = study.run_study(engine.Config(),
                                     {"repetitions": 2, "strategies": ["baseline"]},
                                     on_trial=observe, on_checkpoint=checkpoints.append)
        self.assertEqual(len(originals), 2)
        for result, original in originals:
            self.assertEqual(result, original)
        for sample in report["samples"]:
            self.assertTrue(sample["events"])
            self.assertTrue(sample["business_records"])
            self.assertEqual(sample["arm_id"], "neutral:baseline")
            self.assertGreaterEqual(sample["stats"]["physical_writes"], 0)
        self.assertEqual(checkpoints[-1]["samples"], report["samples"])

    def test_engine_exception_is_observed_once_as_infrastructure_result_without_exception_text(self):
        observed, order = [], []

        def observe(sample, result):
            order.append(("trial", sample["execution_index"]))
            observed.append((sample, result))

        def checkpoint(report):
            order.append(("checkpoint", report["completed"]))

        with patch.object(engine, "run_trial", side_effect=RuntimeError("private-provider-payload")) as execute:
            report = study.run_study(engine.Config(),
                                     {"repetitions": 2, "strategies": ["baseline"]},
                                     on_trial=observe, on_checkpoint=checkpoint)
        self.assertEqual(execute.call_count, 2)
        self.assertEqual(len(observed), 2)
        self.assertEqual(order, [("trial", 1), ("checkpoint", 1),
                                 ("trial", 2), ("checkpoint", 2), ("checkpoint", 2)])
        for sample, result in observed:
            self.assertEqual(sample["status"], "infra_error")
            self.assertFalse(sample["completed"])
            self.assertEqual(sample["execution_violations"][0]["code"], "MODEL_EXECUTION_ERROR")
            self.assertEqual(result["failure_fingerprint"], "MODEL_EXECUTION_ERROR")
        self.assertNotIn("private-provider-payload", json.dumps([report, observed]))
        self.assertEqual(report["arms"][0]["valid_trials"], 0)

    def test_observer_exception_aborts_before_checkpoint_or_next_trial_and_restores_context(self):
        sentinel = object()
        previous = {key: getattr(engine.MODEL_CONTEXT, key, sentinel)
                    for key in engine.MODEL_CONTEXT_FIELDS}
        values = {"remaining": 79, "request_limit": 91,
                  "cancel_check": lambda: False, "usage_records": [{"existing": True}],
                  "budget_exhausted": True}
        observed, checkpoints = [], []

        def observe(sample, result):
            observed.append(sample["execution_index"])
            self.assertNotEqual(engine.MODEL_CONTEXT.remaining, values["remaining"])
            raise OSError("evidence-storage-unavailable")

        try:
            for key, value in values.items():
                setattr(engine.MODEL_CONTEXT, key, value)
            if hasattr(engine.MODEL_CONTEXT, "campaign_stopped_reason"):
                delattr(engine.MODEL_CONTEXT, "campaign_stopped_reason")
            with patch.object(engine, "run_trial", wraps=engine.run_trial) as execute:
                with self.assertRaisesRegex(OSError, "evidence-storage-unavailable"):
                    study.run_study(engine.Config(),
                                    {"repetitions": 2, "prompt_policies": ["neutral", "recovery"]},
                                    on_trial=observe, on_checkpoint=checkpoints.append)
            self.assertEqual(execute.call_count, 1)
            self.assertEqual(observed, [1])
            self.assertEqual(checkpoints, [])
            for key, value in values.items():
                self.assertIs(getattr(engine.MODEL_CONTEXT, key), value)
            self.assertFalse(hasattr(engine.MODEL_CONTEXT, "campaign_stopped_reason"))
        finally:
            for key, value in previous.items():
                if value is sentinel:
                    if hasattr(engine.MODEL_CONTEXT, key):
                        delattr(engine.MODEL_CONTEXT, key)
                else:
                    setattr(engine.MODEL_CONTEXT, key, value)


if __name__ == "__main__":
    unittest.main()
